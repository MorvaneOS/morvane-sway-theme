#!/usr/bin/env python3
"""Builds the MorvaneOS Sway theme: a drop-in for Sway's default config.

    python tools/build.py

Needs only Python. Output goes to config.d/; commit it, it's what the package installs.

Sway's default config (/etc/sway/config, owned by sway) ends with
`include /etc/sway/config.d/*`, so this sets the wallpaper, window colours and bar
colours on top of it. A config of your own in ~/.config/sway replaces the default
and this with it; add `include /etc/sway/config.d/*` to keep the MorvaneOS look.
Terminal colours (foot) come from morvane-wm-theme.
"""

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Keep in step with the window colours in morvane-gtk-theme
PASTEL = '#F4A6C6'
NIGHT = '#120C16'
PAPER = '#F5EEF3'
WHITE = '#FFFFFF'
ACTIVE_BG = '#1A1220'
INACTIVE_BG = '#150F1A'
BORDER = '#2A1C32'
SELECTED = '#4A3552'
MUTED = '#A898AC'
DIM = '#8F7F96'
URGENT = '#F0506E'
URGENT_BG = '#B3261E'

WALLPAPER = '/usr/share/backgrounds/morvaneos/twilight.png'

CONFIG = f'''\
# MorvaneOS look for Sway: generated by tools/build.py in morvane-sway-theme, edit that instead.
# Included by Sway's default config. Settings here override the ones above them there.

output * bg {WALLPAPER} fill

# The focused window has a Pastel Pink border as well as brighter title text, so it
# isn't told apart by colour alone.
#                       border     background  text      indicator  child_border
client.focused          {PASTEL}    {ACTIVE_BG}     {PAPER}   {PASTEL}    {PASTEL}
client.focused_inactive {BORDER}    {ACTIVE_BG}     {MUTED}   {BORDER}    {BORDER}
client.unfocused        {BORDER}    {INACTIVE_BG}     {DIM}   {BORDER}    {BORDER}
client.urgent           {URGENT}    {URGENT_BG}     {WHITE}   {URGENT}    {URGENT}

# The default config's bar
bar bar-0 {{
    colors {{
        background {ACTIVE_BG}
        statusline {PAPER}
        separator {BORDER}
        #                  border   background  text
        focused_workspace  {PASTEL}  {PASTEL}     {NIGHT}
        active_workspace   {SELECTED}  {SELECTED}     {PAPER}
        inactive_workspace {ACTIVE_BG}  {ACTIVE_BG}     {MUTED}
        urgent_workspace   {URGENT}  {URGENT_BG}     {WHITE}
        binding_mode       {SELECTED}  {SELECTED}     {PAPER}
    }}
}}
'''


def build() -> None:
	out = ROOT / 'config.d'
	shutil.rmtree(out, ignore_errors=True)
	out.mkdir()
	(out / '50-morvane-theme.conf').write_text(CONFIG)
	print('Built the Sway drop-in.')


if __name__ == '__main__':
	build()
